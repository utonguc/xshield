<h1>Veri Silme Talimatları</h1>
<p class="upd">Son güncelleme: 19 Haziran 2026</p>

<p>
	goX (bir xShield ürünü) olarak, kişisel verilerinizin silinmesini talep etme hakkınıza saygı
	duyuyoruz. Bu sayfa, verilerinizin nasıl silineceğini ve talebi nasıl ileteceğinizi açıklar.
</p>

<h2>Nasıl talep edersiniz?</h2>
<p>
	<a href="mailto:info@xshield.com.tr?subject=Veri%20Silme%20Talebi">info@xshield.com.tr</a>
	adresine, konu satırına <strong>“Veri Silme Talebi”</strong> yazarak e-posta gönderin.
	Talebinizi doğrulayabilmemiz için, verdiğiniz bağlantı kimliğini (örn. doğrulamada kullandığınız
	e-posta veya telefon/WhatsApp numarası) belirtin.
</p>

<h2>Hangi veriler silinir?</h2>
<ul>
	<li>Bağlantı kimliğiniz (e-posta / telefon / WhatsApp numarası).</li>
	<li>Tercihe bağlı verdiğiniz anket yanıtları ve bildirim tercihleri.</li>
</ul>

<h2>Yasal saklama istisnası</h2>
<p>
	5651 sayılı Kanun gereği tutulması zorunlu olan internet erişim kayıtları (MAC/IP ve zaman
	bilgisi), mevzuatın öngördüğü saklama süresi (asgari 2 yıl) dolmadan silinemez. Bu süre
	dolduğunda ilgili kayıtlar otomatik olarak imha edilir.
</p>

<h2>Süre</h2>
<p>
	Talebiniz, KVKK’nın öngördüğü süre içinde (en geç 30 gün) sonuçlandırılır ve sonuç tarafınıza
	bildirilir.
</p>

