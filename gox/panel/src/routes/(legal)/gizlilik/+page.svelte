<h1>Gizlilik Politikası</h1>
<p class="upd">Son güncelleme: 19 Haziran 2026</p>

<p>
	goX, işletmelere misafir Wi-Fi karşılama ve yönetim hizmeti sunan bir xShield ürünüdür
	(“goX”, “biz”). Bu politika; misafir Wi-Fi ağına bağlanan ziyaretçilerin ve panel
	kullanıcılarının verilerinin nasıl işlendiğini açıklar ve 6698 sayılı Kişisel Verilerin
	Korunması Kanunu (KVKK) kapsamında aydınlatma metni niteliğindedir.
</p>

<h2>İşlenen veriler</h2>
<ul>
	<li><strong>Bağlantı kimliği:</strong> giriş yönteminize göre e-posta adresi, telefon/WhatsApp numarası veya erişim kodu.</li>
	<li><strong>Teknik kayıtlar (5651):</strong> cihaz MAC adresi, IP adresi, bağlantı başlangıç/bitiş zamanı.</li>
	<li><strong>Panel kullanıcıları:</strong> ad, e-posta ve hesap bilgileri.</li>
</ul>
<p>İnternet trafiğinizin içeriği (gezdiğiniz siteler, mesajlarınız) izlenmez ve saklanmaz.</p>

<h2>İşleme amaçları ve hukuki sebep</h2>
<ul>
	<li><strong>Yasal yükümlülük (5651 sayılı Kanun):</strong> internet erişim kayıtlarının tutulması ve zaman damgasıyla saklanması.</li>
	<li><strong>Hizmetin sunulması:</strong> misafir doğrulaması ve internet erişiminin sağlanması.</li>
	<li><strong>Açık rıza:</strong> tercihe bağlı anket ve bildirimler.</li>
</ul>

<h2>WhatsApp ve e-posta ile doğrulama</h2>
<p>
	WhatsApp ile giriş seçeneğinde, doğrulamayı başlatmak için yalnızca tarafınızca gönderilen
	mesajdaki doğrulama kodu ve gönderen telefon numarası işlenir; bu entegrasyon Meta Platforms
	WhatsApp Business Platform üzerinden sağlanır. E-posta ile girişte doğrulama kodu, girdiğiniz
	e-posta adresine gönderilir. Doğrulama amaçlı bu kodlar kısa sürede geçersiz olur; mesaj
	içerikleriniz saklanmaz.
</p>

<h2>Saklama süreleri</h2>
<ul>
	<li>5651 kapsamındaki erişim kayıtları: ilgili mevzuatın öngördüğü süre boyunca (asgari 2 yıl).</li>
	<li>Doğrulama kodları: birkaç dakika ile en çok birkaç saat.</li>
</ul>

<h2>Aktarım</h2>
<p>
	Veriler, hizmetin sunulduğu işletme (veri sorumlusu) ve yasal olarak yetkili merciler dışında
	üçüncü kişilerle paylaşılmaz. WhatsApp doğrulaması için numaranız teknik olarak Meta üzerinden
	iletilir.
</p>

